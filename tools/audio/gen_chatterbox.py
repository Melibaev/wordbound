# A name in front of the line is a caption for the reader, not words to speak.
# System stamps (Count:, Word lost:) stay in the audio. Only a remembered voice is stripped.
QUOTE_VOICE = (
    (re.compile(r"^Mom:\s+", re.I), "mom"),
    (re.compile(r"^A voice from up there:\s+", re.I), "mom"),
    (re.compile(r"^The voice:\s+", re.I), "mom"),
)


def quote_who(line):
    en = (line.get("en") or "").strip()
    for rx, who in QUOTE_VOICE:
        if rx.match(en):
            return who
    return None


def char_of(line):
    q = quote_who(line)
    if q:
        return q
    t = line.get("type", "speech")
    who = line.get("voice") or line.get("who")
    if t == "system" and not line.get("voice"):
        who = "system"
    if t == "narration" and not who:
        who = "narration"
    return who if who in REF_SRC else "dan"


def R(p):
    return re.compile(p, re.I)

RX_WHISPER = R(r"whisper|hushed|hush\b|murmur|barely audible")
RX_TIRED = R(r"tired|exhaust|weary|sad\b|guilt|heavy|regret|sorry|grief|defeat|hoarse|sigh|small and|bittersweet|dazed|awed")
RX_TENSE = R(r"frighten|afraid|terrif|scared|nervous|shak|uneasy|wary|baffled|startled|breathless|confus|puzzl|panic|trembl|worried|anxious|urgent|tight with fear|fear")
RX_ANGRY = R(r"furious|angry|indignant|annoy|outrag|offended|defensive|scoff|irritat|snappy|fierce|raw|ragged|bellow|thunder|roar")
RX_CHEER = R(r"cheerful|bright|cocky|grin|delight|cheeky|pleased|friendly|booming|amused|excited|overjoyed|joy|hopeful|thrilled|proud|warm|playful|sly|fast kid|boy|mischief|smile")
RX_COLD = R(r"flat|cold|deadpan|blunt|monotone|dry|calm|steady|clear|matter.of.fact|plain|curt|clipped|dismiss|bored|firm|measured|low")


def bucket_of(line, char):
    t = line.get("type", "speech")
    d = (line.get("delivery") or "")
    if char == "system":
        return "system"
    if char == "silent":
        return "eerie"
    if char == "keeper":
        return "smooth"
    if char == "mom":
        if re.search(r"eerie|too perfect|too even|tower", d, re.I):
            return "eerie"
        return "warm"
    if t == "shout":
        if RX_ANGRY.search(d) or re.search(r"furious|desperate|frantic|panic", d, re.I):
            return "shout"
        if re.search(r"excited|overjoyed|hopeful|theatrical|joy|relief", d, re.I):
            return "angry"      # loud and bright, but not hoarse
        return "shout"
    if t == "narration" and not line.get("voice"):
        return "whisper" if RX_WHISPER.search(d) else "narr"
    if RX_WHISPER.search(d):
        return "whisper"
    if RX_TENSE.search(d) and not RX_COLD.search(d.split(",")[0]):
        return "tense"
    if RX_ANGRY.search(d):
        return "angry"
    if RX_TIRED.search(d):
        return "tired"
    if RX_CHEER.search(d):
        return "cheer" if char in ("pip", "trader", "lina_human") or re.search(r"cheer|bright|delight|excit|joy|grin", d, re.I) else "warm"
    if RX_COLD.search(d):
        return "cold"
    if t == "thought":
        return "tired"
    return "calm"


def speak_text(line):
    t = line.get("tts_text") or line["en"]
    if not line.get("tts_text"):
        raw = t.strip()
        for rx, _who in QUOTE_VOICE:
            raw = rx.sub("", raw, count=1)
        t = raw
    t = GA.clean(t)
    t = re.sub(r"<\s*(short pause|pause|long pause)\s*>", ", ", t)
    t = re.sub(r"<\s*(sigh|breath|gasp|laugh|cough)[^>]*>", " ", t)
    t = re.sub(r"<[^>]+>", " ", t)
    t = re.sub(r"\s*\.\.\.\s*", ", ", t).strip()      # ellipses get read as "dot" / stumble: use a comma pause
    t = re.sub(r"^[,\s]+", "", t)
    t = re.sub(r"([.!?])\s*,", r"\1", t)
    t = re.sub(r",\s*([.!?])", r"\1", t)
    t = re.sub(r"\s+", " ", t)
    return t


def params_for(char, bucket):
    exa, cfg, temp, mood, tgt = BUCKETS[bucket]
    cfg = min(0.9, max(0.1, cfg + FX.get(char, {}).get("cfg_off", 0.0)))
    return {"exaggeration": exa, "cfg_weight": cfg, "temperature": temp, "mood": mood, "target_db": tgt}


def job_hash(text, char, bucket, delivery):
    p = params_for(char, bucket)
    s = "%s|%s|%s|%s|%s|%s" % (text, char, bucket, json.dumps(p, sort_keys=True), json.dumps(FX.get(char, {}), sort_keys=True), VERSION)
    return hashlib.sha1(s.encode()).hexdigest()[:16]


def _lex_job(rel, text):
    """One dictionary/placement clip: narration + calm."""
    t = GA.clean(text)
    return {"rel": rel, "text": t, "char": WORD_CHAR, "bucket": WORD_BUCKET, "delivery": "",
            "hash": job_hash(t, WORD_CHAR, WORD_BUCKET, ""), "line": {"type": "narration", "who": WORD_CHAR, "en": t}}


def collect_words():
    """Same paths as gen_audio.py --words: audio/w/<id>.mp3, <id>-ex.mp3, f-<slug>.mp3."""
    jobs = []
    words = GA.load(os.path.join(DATA, "words.json"))
    for w in words:
        jobs.append(_lex_job("w/%s.mp3" % w["id"], w["w"]))
        if w.get("ex"):
            jobs.append(_lex_job("w/%s-ex.mp3" % w["id"], w["ex"]))
    heads = {w["w"].lower() for w in words}
    seen = set()
    for w in words:
        for f in w.get("forms", []):
            fl = f.replace(chr(0x2019), "'").replace(chr(0x2018), "'").lower()
            if fl in heads or GA.slug(fl) in seen:
                continue
            seen.add(GA.slug(fl))
            jobs.append(_lex_job("w/f-%s.mp3" % GA.slug(fl), fl))
    return jobs


def collect_placement():
    """Same paths as gen_audio.py --placement: audio/p/<i>.mp3 and p/v-<slug>.mp3."""
    jobs = []
    words = GA.load(os.path.join(DATA, "words.json"))
    plc = GA.load(os.path.join(DATA, "placement.json"))
    for i, it in enumerate(plc.get("listening", [])):
        jobs.append(_lex_job("p/%d.mp3" % i, it["audio"]))
    heads = {w["w"].lower() for w in words}
    seen = set()
    for it in plc.get("vocab", []):
        w = it["word"]
        if w.lower() in heads or GA.slug(w) in seen:
            continue
        seen.add(GA.slug(w))
        jobs.append(_lex_job("p/v-%s.mp3" % GA.slug(w), w))
    return jobs


def collect(episode=None, words=False, placement=False):
    """-> list of dict(rel,text,char,bucket,delivery,hash,line).
    Default (no flags): episode dialogue only. Pass words/placement explicitly.
    """
    jobs = []
    if words or placement:
        if words:
            jobs.extend(collect_words())
        if placement:
            jobs.extend(collect_placement())
        return jobs
    story = GA.load(os.path.join(DATA, "story.json"))
    for ep in story["episodes"]:
        if episode and ep["id"] != episode:
            continue
        path = os.path.join(DATA, ep["file"])
        if not os.path.isfile(path):
            continue
        d = GA.load(path)
        for pi, p in enumerate(d["panels"], 1):
            for li, ln in enumerate(p["lines"], 1):
                if ln.get("type") == "narration-ru" or not ln.get("en"):
                    continue
                ch = char_of(ln)
                b = bucket_of(ln, ch)
                text = speak_text(ln)
                jobs.append({"rel": "%s/%02d-%02d.mp3" % (ep["id"], pi, li), "text": text, "char": ch, "bucket": b,
                             "delivery": ln.get("delivery", ""), "hash": job_hash(text, ch, b, ln.get("delivery")), "line": ln})
    return jobs


def current_set():
    """relpaths whose Chatterbox audio is up to date (gen_audio.py / gen_gemini.py skip these)."""
    if not os.path.isfile(STATE):
        return set()
    st = GA.load(STATE)
    jobs = collect() + collect_words() + collect_placement()
    return {j["rel"] for j in jobs if st.get(j["rel"]) == j["hash"] and os.path.isfile(os.path.join(OUT, j["rel"]))}


# ---- audio helpers (numpy / librosa) -----------------------------------------------------------------
def load_audio(p, sr=SR):
    import librosa
    y, _ = librosa.load(p, sr=sr, mono=True)
    return y


def rms_db(y, thr_rel=0.1):
    import numpy as np
    n = 512
    fr = np.array([np.sqrt(np.mean(y[i:i + n] ** 2)) for i in range(0, max(1, len(y) - n), n // 2)])
    if len(fr) == 0:
        return -90.0
    act = fr > fr.max() * thr_rel
    return float(20 * np.log10(np.sqrt(np.mean(fr[act] ** 2)) + 1e-9))


def set_rms(y, target_db):
    import numpy as np
    g = 10 ** ((target_db - rms_db(y)) / 20)
    return y * g


def resample_pitch(y, st, tempo):
    """Pitch by resampling (clean), then time-stretch so the final speed multiplier == tempo (None: keep resample speed)."""
    import librosa, numpy as np
    if not st:
        if tempo and abs(tempo - 1) > 0.01:
            return librosa.effects.time_stretch(y, rate=tempo)
        return y
    r = 2 ** (st / 12.0)
    y2 = librosa.resample(y, orig_sr=SR, target_sr=SR / r)       # faster + higher
    if tempo and abs(tempo - r) > 0.01:
        y2 = librosa.effects.time_stretch(y2, rate=tempo / r)
    return y2


def whisperize(y, mix):
    """Random-phase STFT resynthesis (intelligible whisper) mixed with the original."""
    import librosa, numpy as np
    S = librosa.stft(y, n_fft=1024, hop_length=256)
    rng = np.random.default_rng(7)
    ph = np.exp(1j * rng.uniform(0, 2 * np.pi, S.shape))
    w = librosa.istft(np.abs(S) * ph, hop_length=256, length=len(y))
    w = set_rms(w, rms_db(y))
    return (1 - mix) * y + mix * w


def reverb(y, rt60, mix):
    import numpy as np
    from scipy.signal import fftconvolve
    n = int(SR * min(rt60 * 1.3, 1.6))
    t = np.arange(n) / SR
    rng = np.random.default_rng(3)
    ir = rng.standard_normal(n) * np.exp(-6.9 * t / rt60)
    ir[: int(0.004 * SR)] *= 0.2
    ir /= np.sqrt(np.sum(ir ** 2))
    wet = fftconvolve(y, ir)[: len(y) + int(0.25 * SR)]
    dry = np.concatenate([y, np.zeros(len(wet) - len(y))])
    wet = set_rms(wet, rms_db(dry)) if rms_db(dry) > -80 else wet
    return (1 - mix) * dry + mix * wet


def even(y, amount=0.8):
    """Slow AGC: makes loudness very even (System voice)."""
    import numpy as np
    n = 480
    out = y.copy()
    fr = np.array([np.sqrt(np.mean(y[i:i + n] ** 2)) + 1e-6 for i in range(0, len(y), n)])
    ref = np.percentile(fr, 80)
    g = np.clip((ref / fr) ** amount, 0.25, 3.0)
    g[fr < 0.01 * ref] = 1.0
    from scipy.ndimage import uniform_filter1d
    g = uniform_filter1d(g, 3)
    gs = np.repeat(g, n)[: len(y)]
    return out * gs


def robot(y):
    import numpy as np
    from scipy.signal import butter, sosfilt
    sos = butter(2, [140, 7000], btype="band", fs=SR, output="sos")
    y = sosfilt(sos, y)
    d = int(0.0028 * SR)                       # short comb = faint metallic ring
    c = y.copy(); c[d:] += 0.30 * y[:-d]
    y = c
    y = even(y, 0.85)
    return y


def breathy(y, mix=0.25):
    return whisperize(y, mix)


def soft_limit(y, drive=1.0, ceil=0.95):
    import numpy as np
    if drive != 1.0:
        y = np.tanh(y * drive) / np.tanh(drive)
    pk = np.abs(y).max()
    if pk > ceil:
        y = np.tanh(y / pk * 1.4) / np.tanh(1.4) * ceil
    return y


def postprocess(y, char, bucket, delivery=""):
    import numpy as np
    fx = dict(FX.get(char, {}))
    tgt = BUCKETS[bucket][4]
    pitch, tempo = fx.get("pitch", 0.0), fx.get("tempo")
    if char == "silent" and re.search(r"child|thin|small|girl", delivery, re.I):
        pitch, tempo = 2.0, None         # stolen child voice: higher, thin
    y = resample_pitch(y, pitch, tempo)
    if bucket == "whisper" and char not in ("silent",):
        y = breathy(y, 0.25)
    for e in fx.get("extra", []):
        if e == "robot":
            y = robot(y)
        elif e == "whisperize":
            y = whisperize(y, 0.45 if re.search(r"whisper|hushed|breathy|thin", delivery, re.I) else 0.3)
    if "reverb" in fx:
        y = reverb(y, *fx["reverb"])
    y = y / (np.abs(y).max() + 1e-9) * 0.5
    y = GA.trim(y.astype("float32"))
    if bucket in ("shout", "angry"):
        y = soft_limit(y, drive=1.8)               # a little saturation = strained, louder voice
    y = set_rms(y, tgt)
    y = soft_limit(y)
    return y.astype("float32")


# ---- reference banks ---------------------------------------------------------------------------------
def build_base_refs():
    import numpy as np, soundfile as sf
    os.makedirs(REFDIR, exist_ok=True)
    paths = {}
    for ch, srcs in REF_SRC.items():
        p = os.path.join(REFDIR, "%s_base.wav" % ch)
        if not os.path.isfile(p):
            parts = []
            for s in srcs:
                y = load_audio(s)
                y = y / (np.abs(y).max() + 1e-9) * 0.5
                y = GA.trim(y)[: int(SR * 9)]
                parts.append(set_rms(y, -22))
                parts.append(np.zeros(int(0.15 * SR), np.float32))
            y = np.concatenate(parts)[: int(SR * 9.5)]
            sf.write(p, y.astype("float32"), SR)
        paths[ch] = p
    return paths


def build_agit_refs(model, base):
    import numpy as np, soundfile as sf, torch
    out = {}
    for ch, (exa, cfg) in AGIT_CHARS.items():
        p = os.path.join(REFDIR, "%s_agit.wav" % ch)
        if not os.path.isfile(p):
            parts = []
            for i, t in enumerate(AGIT_TEXT):
                torch.manual_seed(100 + i)
                w = model.generate(t, audio_prompt_path=base[ch], exaggeration=exa, cfg_weight=cfg, temperature=0.9)
                y = w.squeeze().cpu().numpy().astype("float32")
                y = y / (np.abs(y).max() + 1e-9) * 0.5
                parts += [GA.trim(y), np.zeros(int(0.1 * SR), np.float32)]
            y = np.concatenate(parts)[: int(SR * 9.5)]
            sf.write(p, set_rms(y, -20).astype("float32"), SR)
            log("built agitated ref for %s (%.1fs)" % (ch, len(y) / SR))
        out[ch] = p
    return out


class Synth:
    def __init__(self):
        import torch
        from chatterbox.tts import ChatterboxTTS
        self.torch = torch
        self.m = ChatterboxTTS.from_pretrained(device="cuda" if torch.cuda.is_available() else "cpu")
        self.base = build_base_refs()
        self.agit = build_agit_refs(self.m, self.base)

    def ref(self, char, mood):
        if mood == "agit" and char in self.agit:
            return self.agit[char]
        return self.base[char]

    def gen(self, text, char, bucket, seed, tweak=0):
        P = params_for(char, bucket)
        exa, cfg, temp = P["exaggeration"], P["cfg_weight"], P["temperature"]
        mood = P["mood"]
        if tweak == 1:                 # steadier retry (loudness/energy is restored in post)
            exa, cfg, temp = max(0.25, exa - 0.2), min(0.8, cfg + 0.15), max(0.5, temp - 0.1)
        elif tweak == 2:
            exa, cfg, temp, mood = max(0.25, exa - 0.45), min(0.85, cfg + 0.25), 0.6, "base"
        self.torch.manual_seed(seed)
        w = self.m.generate(text, audio_prompt_path=self.ref(char, mood), exaggeration=exa, cfg_weight=cfg,
                            temperature=temp)
        return w.squeeze().cpu().numpy().astype("float32")


def qa_ok(r, text, char, bucket):
    """-> (ok, penalty)"""
    n = len(text)
    act = r["dur"] - r["lead"] - r["trail"]
    exp = n / 13.0
    pen = r.get("wer", 0.0)
    thr = 0.25 if char == "silent" or bucket == "whisper" else 0.15
    bad = []
    if r.get("wer", 0) > thr:
        bad.append("wer")
    if act < 0.25 * exp or act > 2.6 * exp + 1.0:
        bad.append("pace"); pen += 0.5
    if r["clip_frac"] > 0.003:
        bad.append("clip"); pen += 0.5
    if r["rms_db"] < -50:
        bad.append("silent"); pen += 2
    return (not bad), pen, bad


def roundtrip(y):
    import tempfile
    fd, p = tempfile.mkstemp(suffix=".mp3", dir=os.path.join(MODELS, "cb_refs"))
    os.close(fd)
    try:
        with open(p, "wb") as f:
            f.write(GA.encode(y.astype("float32"), BITRATE))
        return load_audio(p)
    finally:
        os.remove(p)


def render_line(S, job, seed, qa):
    """Generate with QA loop. Returns (audio float32, qa dict, tries)."""
    best = None
    for attempt in range(3):
        raw = S.gen(job["text"], job["char"], job["bucket"], seed + attempt * 7919, tweak=attempt)
        y = postprocess(raw, job["char"], job["bucket"], job["delivery"])
        r = qa.analyse(roundtrip(y), SR, job["text"])       # judge what the learner will actually hear (MP3)
        ok, pen, bad = qa_ok(r, job["text"], job["char"], job["bucket"])
        log("  try %d %s: %s wer=%.2f cps=%.1f f0=%.0f rms=%.1f %s heard=%r" % (
            attempt + 1, job["rel"], "OK" if ok else "BAD" + str(bad), r.get("wer", 0), r.get("cps", 0), r["f0"],
            r["rms_db"], "", r.get("hyp", "")))
        if best is None or pen < best[2]:
            best = (y, r, pen, attempt + 1)
        if ok:
            break
    return best[0], best[1], best[3]


def save_mp3(y, path):
    import numpy as np
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(GA.encode(y.astype("float32"), BITRATE))
    # verify non-silent after decode
    z = load_audio(path)
    assert rms_db(z) > -50 and np.abs(z).max() > 0.02, "silent MP3: " + path


def run_pack(S, qa, seed):
    import librosa
    pack = os.path.join(TT, "pack")
